// v6 smoke: the single page, screenshots, page errors.
const { chromium } = require('/opt/npm-tools/node_modules/playwright');
const path = require('path');
const FILE = 'file://' + path.join(__dirname, '..', 'dist', 'PFT_Interpreter_standalone.html');
(async () => {
  const browser = await chromium.launch();
  const ctx = await browser.newContext({ viewport: { width: 1380, height: 900 } });
  const page = await ctx.newPage();
  const errs = [];
  page.on('pageerror', e => errs.push('pageerror: ' + e.message));
  page.on('console', m => { if (m.type() === 'error' && !/fonts\.g|ERR_|Failed to load resource/.test(m.text())) errs.push('console: ' + m.text()); });
  await page.goto(FILE);
  await page.waitForSelector('#top');
  await page.screenshot({ path: 'shots/v6_01_empty.png', fullPage: true });
  await page.selectOption('#qs', { label: 'Full PFT' });
  await page.locator('.tchip[data-test="sixmw"]').click();
  await page.locator('[data-field="ctx.age"] input').fill('64');
  await page.locator('[data-field="ctx.sex"] .ch[data-v="F"]').click();
  await page.locator('[data-field="ctx.ht"] input').fill('165');
  await page.locator('[data-field="ctx.wt"] input').fill('82');
  await page.locator('[data-field="spiro.ratio"] .sg[data-v="low"]').click();
  await page.locator('[data-cell="spiro.fev1.z"] input').fill('-2.9');
  await page.locator('[data-cell="spiro.fev1_abs"] input').fill('1.62');
  await page.locator('[data-cell="spiro.fev1_pct"] input').fill('58');
  await page.locator('[data-field="spiro.fvc"] .sg[data-v="wnl"]').click();
  await page.locator('[data-cell="spiro.fvc_abs"] input').fill('3.10');
  await page.locator('input[data-bd-toggle]').check();
  await page.locator('[data-cell="bd.fev1_post"] input').fill('1.98');
  await page.locator('[data-prior-add="spiro"]').click();
  await page.locator('[data-cell="prior.fev1"] input').first().fill('1.90');
  await page.locator('[data-prior-dates="spiro"] .qd .lnk', { hasText: '1 yr' }).first().click();
  await page.locator('[data-field="vol.tlc"] .sg[data-v="mild"]').click();
  await page.locator('[data-field="vol.rvtlc"] .sg[data-v="wnl"]').click();
  await page.locator('[data-field="dlco.dlco"] .sg[data-v="mod"]').click();
  await page.locator('[data-field="dlco.basis"] .ch[data-v="un"]').click();
  await page.locator('[data-cell="dlco.hb"] input').fill('10.4');
  await page.locator('[data-cell="dlco.dlco_pct"] input').fill('52');
  await page.locator('[data-cell="sixmw.dist"] input').fill('380');
  await page.locator('[data-cell="sixmw.spo2_base"] input').fill('96');
  await page.locator('[data-cell="sixmw.spo2_nadir"] input').fill('87');
  await page.screenshot({ path: 'shots/v6_02_full.png', fullPage: true });
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: 'shots/v6_03_top.png', fullPage: false });
  console.log(await page.evaluate(() => window.__pft.result.text));
  await page.locator('#theme').click();
  await page.screenshot({ path: 'shots/v6_04_dark.png', fullPage: false });
  await page.setViewportSize({ width: 400, height: 800 });
  await page.screenshot({ path: 'shots/v6_05_phone.png', fullPage: true });
  console.log('overflow', await page.evaluate(() => document.documentElement.scrollWidth > document.documentElement.clientWidth + 1));
  console.log('errors:', errs);
  await browser.close();
})().catch(e => { console.error(e); process.exit(1); });
